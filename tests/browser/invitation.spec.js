test('CSV import, deduplication, manual addition, filter, share, export and persistence', async ({ page }, testInfo) => {
  await page.goto('/admin');
  await page.locator('input[type=file]').setInputFiles('public/contoh-tamu.csv');
  await expect(page.getByRole('dialog', { name: '' })).toBeVisible();
  await page.getByRole('button', { name: 'Impor 3 tamu' }).click();
  await expect(page.locator('tbody tr')).toHaveCount(3);
  await page.locator('input[type=file]').setInputFiles('public/contoh-tamu.csv');
  await page.getByRole('button', { name: 'Impor 3 tamu' }).click();
  await expect(page.getByRole('status')).toContainText('3 duplikat dilewati');
  await expect(page.locator('tbody tr')).toHaveCount(3);
  await page.getByRole('button', { name: 'Tambah tamu', exact: true }).click();
  await page.getByLabel('Nama tamu', { exact: true }).fill('Teman & Keluarga ♥');
  await page.getByLabel('Nomor WhatsApp').fill('0811223344');
  await page.getByLabel('Grup', { exact: true }).fill('Sahabat');
  await page.getByRole('button', { name: 'Tambahkan tamu' }).click();
  await expect(page.locator('tbody tr')).toHaveCount(4);
  await page.reload();
  await expect(page.locator('tbody tr')).toHaveCount(4);
  await page.getByLabel('Cari tamu').fill('Teman &');
  await expect(page.locator('tbody tr')).toHaveCount(1);
  const preview = page.getByRole('link', { name: 'Pratinjau undangan Teman & Keluarga ♥' });
  expect(new URL(await preview.getAttribute('href')).searchParams.get('to')).toBe('Teman & Keluarga ♥');
  await page.getByLabel('Alamat website undangan').fill('https://haidar-gita.vercel.app');
  expect(await preview.getAttribute('href')).toContain('https://haidar-gita.vercel.app/');
  await page.evaluate(() => { window.open = (url) => { window.__shared = url; }; });
  await page.getByRole('button', { name: 'Buka WhatsApp untuk Teman & Keluarga ♥' }).click();
  const shared = new URL(await page.evaluate(() => window.__shared));
  expect(shared.host).toBe('wa.me');
  expect(shared.pathname).toBe('/62811223344');
  expect(shared.searchParams.get('text')).toContain('Haidar Syaddad Al Faruqi');
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Ekspor CSV' }).click();
  expect((await downloadEvent).suggestedFilename()).toBe('tamu-gita-haidar.csv');
  await page.getByLabel('Cari tamu').clear();
  await page.evaluate(() => document.fonts.ready);
  await page.screenshot({ path: testInfo.outputPath('admin.png'), fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true);
  await page.getByRole('button', { name: 'Panduan foto' }).click();
  await expect(page.getByText('public/photos/foto_bersama.jpg')).toBeVisible();
});

test('rejects malformed CSV without changing the guest list', async ({ page }) => {
  await page.goto('/admin');
  await page.locator('input[type=file]').setInputFiles({ name: 'invalid.csv', mimeType: 'text/csv', buffer: Buffer.from('name,phone\nBudi,0812') });
  await expect(page.getByRole('status')).toContainText('kolom "nama"');
  await expect(page.locator('tbody tr')).toHaveCount(0);
});
