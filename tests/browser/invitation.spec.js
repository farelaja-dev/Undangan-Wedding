import { test, expect } from '@playwright/test';

test('invitation shows real names, personal guest, working gallery and calendar', async ({ page }, testInfo) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/?to=Bapak%20Budi%20%26%20Ibu%20Sari');
  await expect(page.locator('.cover-recipient strong')).toHaveText('Bapak Budi & Ibu Sari');
  await expect(page.getByRole('navigation')).toHaveCount(0);
  await expect(page.locator('.invitation-shell')).toHaveAttribute('inert', '');
  await page.evaluate(() => document.fonts.ready);
  await page.screenshot({ path: testInfo.outputPath('cover.png') });
  await page.getByRole('button', { name: 'Buka Undangan', exact: true }).click();
  await expect(page.locator('.invitation-cover')).toHaveCount(0);
  await expect(page.locator('.invitation-shell')).not.toHaveAttribute('inert', '');
  await expect(page.locator('.lux-hero-copy')).toHaveCSS('filter', 'blur(0px)');
  await page.screenshot({ path: testInfo.outputPath('opened.png') });
  const prayer = page.locator('#doa .reveal').last();
  await prayer.scrollIntoViewIfNeeded();
  await expect(prayer).toHaveClass(/is-visible/);
  await expect(page.getByRole('heading', { name: 'Haidar Syaddad Al Faruqi' })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Gita Firanddia Putri Ramadhiany' })).toBeVisible();
  await expect(page.getByLabel('Nama lengkap')).toHaveValue('Bapak Budi & Ibu Sari');
  await expect(page.getByRole('button', { name: 'Kirim konfirmasi' })).toBeDisabled();
  await page.getByLabel('Belum bisa hadir', { exact: true }).check();
  await expect(page.getByLabel('Jumlah tamu')).toHaveCount(0);
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Simpan ke kalender' }).click();
  expect((await downloadEvent).suggestedFilename()).toBe('pernikahan-gita-haidar.ics');
  await page.getByRole('button', { name: 'Pilih foto galeri 1' }).click();
  await page.getByRole('button', { name: 'Slide berikutnya' }).click();
  await expect(page.getByRole('button', { name: 'Pilih foto galeri 2' })).toHaveAttribute('aria-pressed', 'true');
  await page.getByRole('button', { name: 'Slide sebelumnya' }).click();
  await page.getByRole('button', { name: 'Perbesar foto 1', exact: true }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.getByRole('button', { name: 'Foto berikutnya' }).click();
  await expect(page.getByRole('dialog')).toContainText('Langkah kecil');
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await page.getByRole('button', { name: 'Jeda efek animasi' }).click();
  await expect(page.locator('.luxury')).toHaveClass(/effects-paused/);
  await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }));
  await page.evaluate(() => document.fonts.ready);
  await page.screenshot({ path: testInfo.outputPath('invitation.png'), fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true);
  expect(errors).toEqual([]);
});

